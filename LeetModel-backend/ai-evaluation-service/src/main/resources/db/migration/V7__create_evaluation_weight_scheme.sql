CREATE TABLE `evaluation_weight_scheme` (
  `id` BIGINT NOT NULL,
  `scheme_code` VARCHAR(64) NOT NULL,
  `scheme_version` VARCHAR(64) NOT NULL,
  `name` VARCHAR(100) NOT NULL,
  `objective` VARCHAR(500) NOT NULL,
  `feature_code` VARCHAR(32) NOT NULL,
  `metric_set_version` VARCHAR(64) NOT NULL,
  `status` VARCHAR(20) NOT NULL,
  `created_by` BIGINT NOT NULL,
  `deactivated_by` BIGINT NULL,
  `deactivated_at` DATETIME NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `uk_scheme_version` (`scheme_version`),
  INDEX `idx_scheme_code_create_time` (`scheme_code`, `create_time`),
  INDEX `idx_feature_status_create_time` (`feature_code`, `status`, `create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI评价版本化权重方案';

CREATE TABLE `evaluation_weight_scheme_item` (
  `id` BIGINT NOT NULL,
  `scheme_id` BIGINT NOT NULL,
  `metric_code` VARCHAR(64) NOT NULL,
  `metric_version` VARCHAR(64) NOT NULL,
  `unit` VARCHAR(32) NOT NULL,
  `normalization_version` VARCHAR(64) NOT NULL,
  `normalization_method` VARCHAR(32) NOT NULL,
  `clipping_policy` VARCHAR(32) NOT NULL,
  `missing_policy` VARCHAR(32) NOT NULL,
  `lower_bound` DECIMAL(30,10) NULL,
  `upper_bound` DECIMAL(30,10) NULL,
  `target_lower_bound` DECIMAL(30,10) NULL,
  `target_upper_bound` DECIMAL(30,10) NULL,
  `boundary_source` VARCHAR(32) NOT NULL,
  `boundary_reference` VARCHAR(200) NOT NULL,
  `weight_percent` DECIMAL(7,4) NOT NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `uk_scheme_metric` (`scheme_id`, `metric_code`),
  INDEX `idx_scheme_item` (`scheme_id`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI评价权重方案指标快照';
