CREATE TABLE `evaluation_dataset` (
  `id` BIGINT NOT NULL,
  `name` VARCHAR(100) NOT NULL,
  `description` VARCHAR(500) NULL,
  `status` VARCHAR(20) NOT NULL,
  `sample_count` INT NOT NULL,
  `created_by` BIGINT NOT NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  INDEX `idx_dataset_create_time` (`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI评审固定评价数据集';

CREATE TABLE `evaluation_sample` (
  `id` BIGINT NOT NULL,
  `dataset_id` BIGINT NOT NULL,
  `submission_id` BIGINT NOT NULL,
  `team_id` BIGINT NOT NULL,
  `problem_id` BIGINT NOT NULL,
  `sort_order` INT NOT NULL,
  `note` VARCHAR(200) NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `uk_dataset_submission` (`dataset_id`, `submission_id`),
  INDEX `idx_dataset_sort` (`dataset_id`, `sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI评审固定评价样本';

CREATE TABLE `evaluation_task` (
  `id` BIGINT NOT NULL,
  `dataset_id` BIGINT NOT NULL,
  `workflow_version` VARCHAR(40) NOT NULL,
  `repeat_count` INT NOT NULL,
  `client_request_id` VARCHAR(64) NOT NULL,
  `status` VARCHAR(20) NOT NULL,
  `total_slots` INT NOT NULL,
  `terminal_slots` INT NOT NULL DEFAULT 0,
  `failed_slots` INT NOT NULL DEFAULT 0,
  `environment_failures` INT NOT NULL DEFAULT 0,
  `validity_score` DECIMAL(5,2) NULL,
  `stability_score` DECIMAL(5,2) NULL,
  `success_rate` DECIMAL(5,2) NULL,
  `latency_score` DECIMAL(5,2) NULL,
  `overall_score` DECIMAL(5,2) NULL,
  `avg_duration_ms` BIGINT NULL,
  `retry_count` INT NOT NULL DEFAULT 0,
  `error_message` VARCHAR(500) NULL,
  `started_at` DATETIME NULL,
  `finished_at` DATETIME NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `uk_client_request` (`client_request_id`),
  INDEX `idx_dataset_version` (`dataset_id`, `workflow_version`, `create_time`),
  INDEX `idx_task_status` (`status`, `create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI评审质量评价任务';

CREATE TABLE `evaluation_run_attempt` (
  `id` BIGINT NOT NULL,
  `task_id` BIGINT NOT NULL,
  `sample_id` BIGINT NOT NULL,
  `repetition_no` INT NOT NULL,
  `attempt_no` INT NOT NULL,
  `status` VARCHAR(20) NOT NULL,
  `failure_type` VARCHAR(20) NULL,
  `score` DECIMAL(5,2) NULL,
  `result_json` LONGTEXT NULL,
  `model_name` VARCHAR(100) NULL,
  `ai_call_id` VARCHAR(64) NULL,
  `duration_ms` BIGINT NULL,
  `error_message` VARCHAR(500) NULL,
  `started_at` DATETIME NULL,
  `finished_at` DATETIME NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `uk_run_attempt` (`task_id`, `sample_id`, `repetition_no`, `attempt_no`),
  INDEX `idx_run_waiting` (`status`, `create_time`),
  INDEX `idx_task_sample` (`task_id`, `sample_id`, `repetition_no`, `attempt_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI评审质量评价运行尝试';
